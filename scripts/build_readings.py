#!/usr/bin/env python3
"""Write readings.js from the verbatim texts in data/rec/.

The site has no build step. This script is only for regenerating the
browser data file after a source text changes. Run it from the repo root:

    python3 scripts/build_readings.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REC = ROOT / "data" / "rec"
OUT = ROOT / "readings.js"


def load(path: Path) -> str:
    data = path.read_bytes()
    if b"\r" in data:
        raise SystemExit(f"{path} contains CR; refusing to change line endings")
    text = data.decode("utf-8")
    if text.endswith("\n"):
        raise SystemExit(f"{path} has a trailing newline; source files do not")
    return text


def main() -> None:
    days = []
    for n in range(1, 90):
        days.append({"n": n, "description": load(REC / f"g{n:02d}.txt")})
    kathismata = []
    for n in range(1, 21):
        kathismata.append({"n": n, "description": load(REC / f"k{n:02d}.txt")})

    payload = json.dumps(
        {"days": days, "kathismata": kathismata},
        ensure_ascii=True,
        indent=2,
    )
    # JSON is a subset of JS here (no U+2028/U+2029; ensure_ascii is on).
    out = (
        "/* Generated by scripts/build_readings.py from data/rec. Do not edit by hand. */\n"
        "const OPTINA_READINGS = "
        + payload
        + ";\n"
        "if (typeof globalThis !== 'undefined') globalThis.OPTINA_READINGS = OPTINA_READINGS;\n"
        "if (typeof module !== 'undefined' && module.exports) {\n"
        "  module.exports = OPTINA_READINGS;\n"
        "}\n"
    )
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(days)} days, {len(kathismata)} kathismata)")


if __name__ == "__main__":
    main()
